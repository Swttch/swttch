import { useLayoutEffect, useRef, useState } from 'react';

/** A title is drawn letter by letter only while it is this fresh; after that it is just text. */
export const TYPEWRITER_FRESH_MS = 3_000;

/** The pause between two letters. */
const STEP_MS = 55;

/** A long title is drawn faster, so that the whole of it never takes longer than this. */
const MAX_TOTAL_MS = 1_600;

/**
 * The text cut into what a person counts as one letter. A Hangul syllable, an
 * emoji or a letter with its accent stays whole instead of being cut mid-way.
 */
export function splitLetters(text: string): string[] {
  const Segmenter = (Intl as unknown as { Segmenter?: SegmenterConstructor }).Segmenter;
  if (Segmenter) {
    const segmenter = new Segmenter(undefined, { granularity: 'grapheme' });
    return Array.from(segmenter.segment(text), (part) => part.segment);
  }
  // A browser without Intl.Segmenter: cut by code point, which still keeps an emoji whole.
  return Array.from(text);
}

/** The part of `Intl.Segmenter` used here, which the project's TypeScript library setting does not declare. */
interface SegmenterConstructor {
  new (locale: string | undefined, options: { granularity: 'grapheme' }): {
    segment(input: string): Iterable<{ segment: string }>;
  };
}

function prefersReducedMotion(): boolean {
  return typeof window !== 'undefined'
    && typeof window.matchMedia === 'function'
    && window.matchMedia('(prefers-reduced-motion: reduce)').matches;
}

interface TypewriterTextProps {
  text: string;
  /**
   * When `text` arrived as a title Claude Code generated by itself (`Date.now()`),
   * or null/undefined for any other text. Only a title that arrived within
   * {@link TYPEWRITER_FRESH_MS} is drawn letter by letter; a title read from a
   * reloaded list or a reopened session is shown at once.
   */
  arrivedAt?: number | null;
  className?: string;
}

/**
 * Text that, when it is a title that has just been generated, appears letter by
 * letter instead of replacing the old one in a single frame.
 *
 * It plays once per text: drawing the same text again (another render, the row
 * scrolling back into view) shows it whole. With "reduce motion" on, it is always
 * whole. A screen reader gets the finished text from the start.
 */
export function TypewriterText({ text, arrivedAt, className }: TypewriterTextProps) {
  // How many letters are shown, or null for all of them.
  const [shownCount, setShownCount] = useState<number | null>(null);
  const playedText = useRef<string | null>(null);

  useLayoutEffect(() => {
    const fresh = arrivedAt != null && Date.now() - arrivedAt < TYPEWRITER_FRESH_MS;
    if (!fresh || prefersReducedMotion() || playedText.current === text) {
      setShownCount(null);
      return;
    }
    playedText.current = text;

    const total = splitLetters(text).length;
    if (total === 0) {
      setShownCount(null);
      return;
    }
    const step = Math.min(STEP_MS, MAX_TOTAL_MS / total);
    let count = 0;
    let finished = false;
    setShownCount(0);
    const timer = setInterval(() => {
      count += 1;
      if (count >= total) {
        finished = true;
        clearInterval(timer);
        setShownCount(null);
        return;
      }
      setShownCount(count);
    }, step);
    return () => {
      clearInterval(timer);
      // Cut short (the effect ran again before the text was drawn out): it has not
      // been played, so the run that follows may play it.
      if (!finished) playedText.current = null;
    };
  }, [text, arrivedAt]);

  // Outside the short time it is being drawn it is a plain span, so a row or a header
  // that holds it is laid out exactly as if it held the text itself.
  if (shownCount === null) return <span className={className}>{text}</span>;

  return (
    <span className={className} aria-label={text}>
      <span aria-hidden="true">{splitLetters(text).slice(0, shownCount).join('')}</span>
    </span>
  );
}
